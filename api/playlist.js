/**
 * StreamForge 24/7 — Master IPTV M3U Playlist Generator (/api/playlist.m3u)
 */

const { ensureFilesInitialized } = require('./_lib/store');

function getBaseUrl(req, store) {
  if (store?.settings?.vercelUrl) {
    return store.settings.vercelUrl.replace(/\/+$/, '');
  }
  const proto = req.headers['x-forwarded-proto'] || 'http';
  const host = req.headers['x-forwarded-host'] || req.headers.host || 'localhost:3000';
  return `${proto}://${host}`;
}

module.exports = async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Content-Type', 'audio/x-mpegurl; charset=utf-8');
  res.setHeader('Content-Disposition', 'inline; filename="streamforge-24x7-playlist.m3u"');

  const store = ensureFilesInitialized();
  const baseUrl = getBaseUrl(req, store);

  const lines = [
    '#EXTM3U x-tvg-url=""',
    '# Generated by StreamForge 24/7 Live TV Engine (Vercel + GitHub Actions)'
  ];

  for (const ch of store.channels || []) {
    if (!ch.enabled) continue;
    const logo = ch.logo || '';
    const category = ch.category || 'Live TV';
    const vercelM3u8 = `${baseUrl}/api/stream/${ch.slug}/index.m3u8`;
    lines.push(
      `#EXTINF:-1 tvg-id="${ch.slug}" tvg-name="${ch.name}" tvg-logo="${logo}" group-title="${category}",${ch.name}`,
      vercelM3u8
    );
  }

  res.statusCode = 200;
  return res.end(lines.join('\n') + '\n');
};
